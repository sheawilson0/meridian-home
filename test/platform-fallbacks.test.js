'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const vm = require('node:vm');

test('Linux retains files and env voice keys without invoking macOS helpers or logging failures', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'linux-fallbacks-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const descriptor = Object.getOwnPropertyDescriptor(process, 'platform');
  Object.defineProperty(process, 'platform', { value: 'linux' });
  t.after(() => Object.defineProperty(process, 'platform', descriptor));
  const cp = require('node:child_process'), execFile = cp.execFile;
  cp.execFile = () => { throw new Error('No system helper should run'); };
  t.after(() => { cp.execFile = execFile; });
  const logs = [];
  const { createStash } = require('../stash');
  const stash = createStash({ dir: path.join(dir, 'stash'), visionSrc: path.join(dir, 'helper.swift'), visionBin: path.join(dir, 'helper'), log: line => logs.push(line) });
  fs.writeFileSync(path.join(dir, 'helper.swift'), 'synthetic helper');
  const bytes = Buffer.from('synthetic image');
  const image = await stash.addFile(bytes, { name: 'sample.png', type: 'image/png' });
  const pdf = await stash.addFile(Buffer.from('synthetic document'), { name: 'sample.pdf', type: 'application/pdf' });
  await stash.settle();
  assert.equal(image.item.kind, 'image'); assert.equal(pdf.item.kind, 'file');
  assert.equal(fs.readFileSync(path.join(dir, 'stash', image.item.file)).equals(bytes), true);
  assert.equal(fs.existsSync(path.join(dir, 'helper')), false);
  assert.deepEqual(logs, []);
  const { createVoice } = require('../voice');
  const voice = createVoice({ dataDir: dir, drafts: {}, env: {} });
  assert.equal((await voice.status()).ready, false);
  const configured = createVoice({ dataDir: dir, drafts: {}, env: { OPENAI_API_KEY: 'synthetic-api-key' } });
  assert.equal((await configured.status()).keySource, 'env');
  const { createFleetPause } = require('../fleet-pause');
  const fleet = createFleetPause({ uid: 123, agentsDir: dir, auditRoot: dir, file: path.join(dir, 'paused.json'), selfPort: 5140, runner: () => { throw new Error('No launchd command should run'); } });
  fs.writeFileSync(path.join(dir, 'synthetic.plist'), 'synthetic plist');
  const service = { name: 'Sample service', url: 'http://127.0.0.1:5148' };
  const info = (await fleet.annotate({ services: [service] })).get(service.name);
  assert.equal(info.pauseMode, 'probe');
  assert.equal((await fleet.pause(service, info)).paused, true);
  assert.equal((await fleet.resume(service.name)).paused, false);
  const source = fs.readFileSync(path.join(__dirname, '../brief-icon.js'), 'utf8');
  const loaded = { exports: {} };
  const load = vm.runInThisContext('(function(require,module,exports,__dirname){' + source + '\n})');
  load(name => name === './brief-art' ? { collection: [] } : require(name.startsWith('./') ? '../' + name.slice(2) : name), loaded, loaded.exports, path.join(__dirname, '..'));
  assert.equal(await loaded.exports.refresh(), null);
  const stop = loaded.exports.start(); stop();
  let status, body;
  await loaded.exports.send({ headers: {} }, { writeHead(code) { status = code; }, end(bytes) { body = bytes; } });
  assert.equal(status, 200); assert.match(body.toString(), /<svg/);
});

test('missing lsof and unsupported launchctl are quiet while real collector failures still report', async () => {
  const source = fs.readFileSync(path.join(__dirname, '../server.js'), 'utf8');
  const body = source.slice(source.indexOf('function run(cmd,'), source.indexOf('function fetchUrl('));
  const errors = []; let calls = 0;
  const context = { JOBS_ENABLED: true, process: { platform: 'linux' }, firstRun: { executable: () => true }, execute: async () => { calls++; throw Object.assign(new Error('absent'), { code: 'ENOENT' }); }, workContext: { getStore: () => ({ errors }) } };
  vm.runInNewContext(body, context);
  assert.equal(await context.run('launchctl', ['list']), null); assert.equal(calls, 0);
  assert.equal(await context.run('lsof', []), null); assert.equal(calls, 1); assert.deepEqual(errors, []);
  await context.run('git', ['status']); assert.equal(errors.length, 1);
});
